# 2. 地図の初期化（日本の中心付近）
m = folium.Map(location=[36.0, 138.0], zoom_start=5, tiles="CartoDB positron")

# 3. カテゴリごとの色定義関数
def get_color(category):
    if '2_' in category: return 'red'       # 禁止・不同意（最も厳しい）
    if '1a_' in category: return 'orange'   # 許可制優位
    if '1b_' in category: return 'orange'   # 届出制優位
    if '3_' in category: return 'purple'    # 許可or同意
    if '5_' in category: return 'green'     # 抑制区域
    if '6_' in category: return 'blue'      # 区域なし許可
    if '7_' in category: return 'gray'      # 届出・協議のみ
    return 'black'

# 4. マーカーのプロット
