    # ポップアップに表示するHTML情報
    popup_text = f"""
    <b>{row['自治体名']}</b><br>
    カテゴリ: {row['7段階カテゴリ']}<br>
    """
    
    folium.CircleMarker(
        location=[row['緯度'], row['経度']],
        radius=6,
        popup=folium.Popup(popup_text, max_width=300),
        color=color,
        fill=True,
        fill_color=color,
        fill_opacity=0.7
    ).add_to(m)

